# ── Color Palette (matches InsightAI frontend) ──────────────────────────────

_NAVY = colors.HexColor("#0f1f44")
_BLUE = colors.HexColor("#4f6ef7")
_BLUE_LIGHT = colors.HexColor("#eef3ff")
_BLUE_SOFTER = colors.HexColor("#f5f8ff")
_GREEN = colors.HexColor("#10b981")
_AMBER = colors.HexColor("#f59e0b")
_RED = colors.HexColor("#ef4444")
